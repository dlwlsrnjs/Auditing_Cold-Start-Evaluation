# ------------------------------------------------------------------ model
class Net(nn.Module):
    def __init__(s):
        super().__init__()
        E = 16
        s.cat = nn.ModuleList([nn.Embedding(len(v) + 1, E) for v in cat_maps.values()])
        s.dx = nn.Embedding(len(dx_vocab) + 1, 32); s.i3 = nn.Embedding(len(i3_vocab) + 1, 16)
        if A.aldi > 0:
            s.aldi_proj = nn.Sequential(nn.Linear(DG.shape[1] if DG is not None else 1, 64),
                                        nn.ReLU(), nn.Linear(64, 32))
        nn.init.normal_(s.dx.weight, std=.01); nn.init.normal_(s.i3.weight, std=.01)
        d_static = E * len(CATS) + 16 + XN.shape[1] - len(HIST)
        d_hist, d_dx = len(HIST), 32
        d_dxt = DG.shape[1] if DG is not None else 0
        d_txt = TX.shape[1] if TX is not None else 0
        d_knn = KN.shape[1] if KN is not None else 0
        d_agt = AG.shape[1] if AG is not None else 0
        d_lab = LB.shape[1] if LB is not None else 0
        s.blocks = ([d_hist, d_dx, d_static] + ([d_dxt] if d_dxt else [])
                    + ([d_txt] if d_txt else []) + ([d_lab] if d_lab else [])
                    + ([d_knn] if d_knn else []) + ([d_agt] if d_agt else []))
        # DA-IFU: availability-conditioned gate per field block
        s.gate = nn.Sequential(nn.Linear(AV.shape[1], 32), nn.ReLU(), nn.Linear(32, len(s.blocks)))
        din = sum(s.blocks)
        s.trunk = nn.Sequential(nn.Linear(din, A.dim), nn.ReLU(), nn.Dropout(0.1),
                                nn.Linear(A.dim, A.dim), nn.ReLU())
        h = A.dim
        s.tw_m = nn.Sequential(nn.Linear(h, 64), nn.ReLU()); s.hd_m = nn.Linear(64, 1)
        cin_r = h + (64 if not A.no_chain else 0)
        s.tw_r = nn.Sequential(nn.Linear(cin_r, 64), nn.ReLU()); s.hd_r = nn.Linear(64, 1)
        cin_l = h + (128 if not A.no_chain else 0)
        s.tw_l = nn.Sequential(nn.Linear(cin_l, 64), nn.ReLU()); s.hd_l = nn.Linear(64, 1)

    def forward(s, i):
        cats = torch.cat([e(CAT[i, k]) for k, e in enumerate(s.cat)], -1)
        xn = XN[i]
        hist = xn[:, 1:1 + len(HIST)]
        static = torch.cat([cats, s.i3(I3[i]), xn[:, :1], xn[:, 1 + len(HIST):]], -1)
        dxb = s.dx(DX[i])
        if A.aldi > 0 and DG is not None:
            proj = s.aldi_proj(DG[i])
            warm = (DX[i] > 0).float().unsqueeze(-1)      # 0 = code unseen in training
            s.last_aldi = (proj, dxb.detach(), warm)       # cached for the distillation loss
            dxb = warm * dxb + (1 - warm) * proj           # cold codes use the projection
        if A.dx_dropout > 0 and s.training:
            keep = (torch.rand(dxb.shape[0], 1, device=dxb.device) > A.dx_dropout).float()
            dxb = dxb * keep
        parts = ([hist, dxb, static] + ([DG[i]] if DG is not None else [])
                 + ([TX[i]] if TX is not None else [])
                 + ([LB[i]] if LB is not None else [])
                 + ([KN[i]] if KN is not None else [])
                 + ([AG[i]] if AG is not None else []))
        if not A.no_daifu:
            gsig = torch.sigmoid(s.gate(AV[i]))                       # (B, n_blocks)
            parts = [p * gsig[:, k:k + 1] for k, p in enumerate(parts)]
        z = s.trunk(torch.cat(parts, -1))
        hm = s.tw_m(z); lm = s.hd_m(hm).squeeze(-1)
        if A.no_chain:
            hr = s.tw_r(z); hl = s.tw_l(z)
        else:
            # DC-MTL: gate the chain by predicted survival - readmission is only defined there
            surv = torch.sigmoid(-lm).unsqueeze(-1).detach()
            hr = s.tw_r(torch.cat([z, hm * surv], -1))
            hl = s.tw_l(torch.cat([z, hm, hr], -1))
        return lm, s.hd_r(hr).squeeze(-1), s.hd_l(hl).squeeze(-1)

def run(tasks, tag):
    """tasks: subset of {'m','r','l'} to optimise (STL trains one at a time)."""
    torch.manual_seed(A.seed)
    net = Net().to(DEV); opt = torch.optim.Adam(net.parameters(), lr=A.lr)
    bce = nn.BCEWithLogitsLoss(reduction="none"); hub = nn.HuberLoss(reduction="none")
    best, best_state = -1e9, None
    for ep in range(A.epochs):
        net.train(); perm = np.random.permutation(idx_tr)
        for k in range(0, len(perm), A.bs):
            i = T(perm[k:k + A.bs], torch.long)
            lm, lr_, ll = net(i)
            loss = 0.
            if "m" in tasks:
                wi = WI[i]
                loss = loss + A.w_mort * (bce(lm, YM[i]) * wi).sum() / wi.sum().clamp(min=1)
            if "r" in tasks:
                m = MR[i] * WR[i] * WI[i]
                loss = loss + A.w_readmit * (bce(lr_, YR[i]) * m).sum() / m.sum().clamp(min=1)
            if "l" in tasks:
                ml = ML[i]
                loss = loss + A.w_los * (hub(ll, YL[i]) * ml).sum() / ml.sum().clamp(min=1)
            if A.aldi > 0 and hasattr(net, "last_aldi"):
                proj, tgt, warm = net.last_aldi
                nw = warm.sum().clamp(min=1)
                loss = loss + A.aldi * (((proj - tgt) ** 2).mean(-1, keepdim=True) * warm).sum() / nw
            opt.zero_grad(); loss.backward(); opt.step()
        sc = evaluate(net, idx_va, tasks)["_sel"]
        if sc > best: best, best_state = sc, {k: v.clone() for k, v in net.state_dict().items()}
        print(f"  [{tag}] ep{ep} val_sel={sc:.4f}", flush=True)
    net.load_state_dict(best_state); return net

@torch.no_grad()
def predict(net, ix):
    net.eval(); out = [[], [], []]
    for k in range(0, len(ix), 16384):
        i = T(ix[k:k + 16384], torch.long); a, b, c = net(i)
        out[0].append(a.cpu()); out[1].append(b.cpu()); out[2].append(c.cpu())
    return [torch.cat(o).numpy() for o in out]

def _auc(y, p):
    return float(roc_auc_score(y, p)) if len(np.unique(y)) > 1 else float("nan")
def _ap(y, p):
    return float(average_precision_score(y, p)) if len(np.unique(y)) > 1 else float("nan")

def _rank_metrics(y, p, budgets=(0.01, 0.05, 0.10)):
    """ColdLLM-style Recall@K / NDCG@K where the candidate pool is the admission set and
    K is an alert budget (fraction of the pool)."""
    out = {}
    n = len(y); order = np.argsort(-p); ys = y[order]; P = ys.sum()
    for b in budgets:
        k = max(int(round(b * n)), 1)
        out[f"recall@{int(b*100)}"] = float(ys[:k].sum() / max(P, 1))
        gains = ys[:k] / np.log2(np.arange(2, k + 2))
        ideal = np.ones(int(min(P, k))) / np.log2(np.arange(2, min(P, k) + 2))
        out[f"ndcg@{int(b*100)}"] = float(gains.sum() / max(ideal.sum(), 1e-9))
    return out

def evaluate(net, ix, tasks=("m", "r", "l")):
    pm, pr, pl = predict(net, ix)
    r = {}
    r["mort_auroc"] = _auc(Y_M[ix], pm); r["mort_auprc"] = _ap(Y_M[ix], pm)
    for k, v in _rank_metrics(Y_M[ix], pm).items(): r[f"mort_{k}"] = v
    m = (M_R_EVAL[ix] == 1) if A.eval_uncensored else (M_R[ix] == 1)
    r["readmit_auroc"] = _auc(Y_R[ix][m], pr[m]) if m.sum() else float("nan")
    r["readmit_auprc"] = _ap(Y_R[ix][m], pr[m]) if m.sum() else float("nan")
    los_true = np.expm1(Y_L[ix]); los_pred = np.expm1(pl * los_sd + los_mu)
    r["los_rmse"] = float(np.sqrt(np.mean((los_true - los_pred) ** 2)))
    r["los_mae"] = float(np.mean(np.abs(los_true - los_pred)))
    sel = [r["mort_auroc"] if "m" in tasks else None,
           r["readmit_auroc"] if "r" in tasks else None,
           -r["los_mae"] / 10 if "l" in tasks else None]
    r["_sel"] = float(np.nanmean([s for s in sel if s is not None]))
    return r

def blocks(net, ix):
    """cold-block breakdown on the test split"""
    sub = d.iloc[ix]
    res = {}
    for uname, u in [("warmU", 0), ("coldU", 1)]:
        for iname, i in [("warmD", 0), ("coldD", 1)]:
            sel = np.where((sub.cold_user_first_admission.values == u) &
                           (sub.cold_item_rare_dx.values == i))[0]
            if len(sel) < 50: continue
            res[f"{uname}_{iname}"] = dict(n=int(len(sel)), **{k: v for k, v in
                                     evaluate(net, ix[sel]).items() if not k.startswith("_")})
    # sanity stratum: ICU-exposed admissions only, for comparability with ICU-only mortality
    # benchmarks in the literature (general-admission AUROC is not directly comparable - the
    # denominator here is diluted by low-acuity admissions the model finds trivially easy).
    # note-present stratum: the denominator ClinicalBERT is scored on (it sees text only),
    # so the text-baseline comparison in the paper is like-for-like rather than across
    # different test populations.
    if "NOTE_OK" in globals():
        nsel = np.where(NOTE_OK[ix])[0]
        if len(nsel) >= 50:
            res["note_present"] = dict(n=int(len(nsel)), **{k: v for k, v in
                                       evaluate(net, ix[nsel]).items() if not k.startswith("_")})
    if "has_icu" in sub.columns:
        isel = np.where(sub.has_icu.values == 1)[0]
        if len(isel) >= 50:
            res["icu_only"] = dict(n=int(len(isel)), **{k: v for k, v in
                                   evaluate(net, ix[isel]).items() if not k.startswith("_")})
    return res

