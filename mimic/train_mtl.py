#!/usr/bin/env python3
"""Cold-start hybrid-target MTL on MIMIC-IV (ColdHTL / DA-IFU / DC-MTL, medical instance).

Hybrid target with a conditional-observation funnel (see mimic/build_cohort.py):
    y_mortality  (primary binary, always observed)
      -> y_readmit_30d (dependent binary, observed only if survived AND follow-up uncensored)
         -> y_los_days (continuous core, always observed)

Cold-start blocks:
    cold-user = the patient's first admission -> the whole prior-history feature block is missing
    cold-dx   = rare primary diagnosis, STRICTLY removed from training -> its id embedding is
                never trained, only its ICD-chapter prefix and (optionally) note text generalise

DA-IFU (direction-aware information-flow unit): per-field-block gates conditioned on which blocks
are actually available, so a missing history block or an untrained dx id cannot inject noise into
the shared trunk. DC-MTL: the dependence chain mortality -> readmit -> LOS is passed through the
towers, gated by the predicted survival probability, so the readmit tower only receives signal
where the outcome can be observed at all.

LEAKAGE CONTROL. Excluded from features by construction: discharge_location, dischtime,
days_to_next_admit, is_last_admission, readmit_censored, died_within_window_post_discharge (all
discharge- or future-time). dx frequency is recomputed on the TRAIN split only.

CAVEAT worth stating in the paper: MIMIC-IV `diagnoses_icd` is billing-coded at discharge, so the
principal diagnosis is not strictly known at admission. It is used here as the cold-start ITEM
identity (the entity whose representation must be learned), which is the methodology's premise.
Run with --dx-mode strata to demote it to an evaluation stratum only and quantify its contribution.

Usage:
  python3 mimic/train_mtl.py --seed 42 --mode mtl
  python3 mimic/train_mtl.py --seed 42 --mode stl          # single-task baselines
  python3 mimic/train_mtl.py --seed 42 --mode mtl --no-daifu --no-chain   # ablations
"""
import argparse, json, os, time
import numpy as np, pandas as pd, torch, torch.nn as nn
from sklearn.metrics import roc_auc_score, average_precision_score

ap = argparse.ArgumentParser()
ap.add_argument("--cohort", default="mimic/out/cohort.parquet")
ap.add_argument("--textemb", default=None, help="optional .npy of per-admission note embeddings")
ap.add_argument("--textids", default=None, help="parquet with hadm_id aligned to --textemb rows")
ap.add_argument("--dxemb", default=None, help="optional .npy of per-ICD-code text embeddings")
ap.add_argument("--dxids", default=None, help="parquet with primary_icd aligned to --dxemb rows")
ap.add_argument("--out", default="mimic/out")
ap.add_argument("--seed", type=int, default=42)
ap.add_argument("--mode", choices=["mtl", "stl"], default="mtl")
ap.add_argument("--dx-mode", choices=["input", "strata"], default="input")
ap.add_argument("--aldi", type=float, default=0.0,
                help="ALDI-style warm-to-cold distillation weight. A projection of the frozen "
                     "dx-text embedding is trained to match the learned identity embedding on WARM "
                     "codes only; at test time cold codes are represented by that projection. "
                     "Adapts Huang et al. (SIGIR 2023) to a task with no interaction matrix.")
ap.add_argument("--smote", type=int, default=0,
                help="non-LLM synthetic-row control: this many rows generated by interpolating "
                     "between nearest rare-dx admissions in feature space (SMOTE-style)")
ap.add_argument("--dx-dropout", type=float, default=0.0,
                help="DropoutNet-style stochastic masking of the diagnosis identity block during "
                     "training (identity retained but randomly zeroed). Direct comparator for the "
                     "delete-vs-regularize question: --dx-dropout 0.5 vs --dx-mode strata")
ap.add_argument("--no-daifu", action="store_true")
ap.add_argument("--no-chain", action="store_true")
ap.add_argument("--dim", type=int, default=128)
ap.add_argument("--epochs", type=int, default=8)
ap.add_argument("--bs", type=int, default=4096)
ap.add_argument("--lr", type=float, default=2e-3)
ap.add_argument("--w-mort", type=float, default=1.0)
ap.add_argument("--w-readmit", type=float, default=1.0)
ap.add_argument("--w-los", type=float, default=0.5)
ap.add_argument("--ipcw", action="store_true",
                help="inverse-probability-of-censoring weights on the readmission loss: "
                     "corrects the complete-case bias documented in the cohort EDA "
                     "(censoring is 53%% on cold users vs 29%% on warm)")
ap.add_argument("--ipcw-clip", type=float, default=5.0)
ap.add_argument("--fixed-split", action="store_true",
                help="patient split from rng(0) regardless of --seed (seeds then vary only model "
                     "init/order). Required by the agent-evidence experiments, whose retrieval "
                     "pool must coincide with the train split across seeds")
ap.add_argument("--knn", action="store_true",
                help="retrieval-evidence block: softmax-weighted outcome statistics of the "
                     "K nearest TRAIN admissions (note+dx-text space, same-patient excluded). "
                     "Real cross-patient evidence, recomputed per seed -> no split leakage")
ap.add_argument("--knn-k", type=int, default=32)
ap.add_argument("--agentemb", default=None, help=".npy of agent-evidence embeddings")
ap.add_argument("--agentids", default=None, help="parquet with hadm_id aligned to --agentemb")
ap.add_argument("--personas", default=None,
                help="persona augmentation: parquet from gen_personas.py; each persona becomes a "
                     "full synthetic training row (static features + findings-text block + labels)")
ap.add_argument("--personaemb", default=None, help=".npy aligned with --personas rows")
ap.add_argument("--exclude-early-deaths", type=float, default=0.0,
                help="drop admissions whose LOS is below this many hours, removing deaths that "
                     "occur inside the feature window (leakage sensitivity check)")
ap.add_argument("--mortality-horizon-days", type=float, default=0.0,
                help="optional fixed mortality horizon from admission: deaths with LOS above "
                     "this many days are relabelled negative. With --exclude-early-deaths 48 and "
                     "a value of 30, this evaluates in-hospital death from the 48h landmark "
                     "through day 30 rather than unrestricted subsequent in-hospital mortality")
ap.add_argument("--eval-uncensored", action="store_true",
                help="score the readmission head only on rows whose outcome is actually "
                     "observed, so a naive-basis run is compared with a corrected run on "
                     "identical test rows rather than on its own zero-filled superset")
ap.add_argument("--save-preds", default=None,
                help="write per-test-admission predicted mortality risk to this parquet, so the "
                     "primary endpoint can carry a test-set bootstrap interval (sampling "
                     "variance) rather than only a 5-seed one (initialization variance)")
ap.add_argument("--lab-group", default="",
                help="restrict the laboratory block to one physiological group: renal, heme, coag, "
                     "hepatic, perfusion, or 'count' for the two global summaries (lab_n, "
                     "lab_abn_frac) that belong to no analyte family. Used to test whether the "
                     "gain rests on one analyte family, on broad severity, or on measurement "
                     "intensity alone.")
ap.add_argument("--labsfeat", default=None,
                help="parquet of first-48h lab features (build_labs.py); availability-gated block")
ap.add_argument("--inject-labels", default=None,
                help="ColdLLM-style label injection: parquet(hadm_id, y_mort, y_readmit, conf) for "
                     "admissions in the dropped cold-dx train block; they rejoin training with "
                     "these labels (LOS masked), so the cold region trains through the loss")
ap.add_argument("--readmit-basis", choices=["corrected", "naive"], default="corrected",
                help="naive = refill censored rows with the mechanical 0 (the label a pipeline "
                     "gets if it never notices right-censoring); quantifies the confound's "
                     "model-level damage")
ap.add_argument("--device", default="cuda:0" if torch.cuda.is_available() else "cpu")
ap.add_argument("--hospice-positive", action="store_true",
                help="count discharge-to-hospice survivors as mortality positives. "
                     "hospital_expire_flag is 0 for them, and their rate differs two-fold "
                     "between warm-user and cold-user segments, so the mortality label is "
                     "itself segment-differentially observable -- this arm prices that.")
ap.add_argument("--tag", default="")
A = ap.parse_args()

torch.manual_seed(A.seed); np.random.seed(A.seed)
DEV = A.device
t0 = time.time()
d = pd.read_parquet(A.cohort)
if A.hospice_positive:
    _h = d.discharge_location.astype(str).str.upper().eq("HOSPICE")
    print(f"hospice-positive: {int((_h & d.y_mortality.eq(0)).sum()):,} survivor rows relabelled, "
          f"mortality {d.y_mortality.mean()*100:.2f}% -> ", end="", flush=True)
    d.loc[_h, "y_mortality"] = 1
    print(f"{d.y_mortality.mean()*100:.2f}%", flush=True)
_icu = pd.read_csv("mimic/physionet.org/files/mimiciv/3.1/icu/icustays.csv.gz",
                   usecols=["hadm_id"])
d["has_icu"] = d.hadm_id.isin(set(_icu.hadm_id)).astype(int)
print(f"cohort {len(d):,} admissions, {d.subject_id.nunique():,} patients", flush=True)

# ------------------------------------------------------------------ splits (patient-level)
rng = np.random.default_rng(0 if A.fixed_split else A.seed)
pids = d.subject_id.unique(); rng.shuffle(pids)
n = len(pids); tr_p = set(pids[:int(.7 * n)]); va_p = set(pids[int(.7 * n):int(.8 * n)])
d["split"] = np.where(d.subject_id.isin(tr_p), "train",
             np.where(d.subject_id.isin(va_p), "val", "test"))
# STRICT cold-item: rare-dx admissions never appear in training
d.loc[(d.split == "train") & (d.cold_item_rare_dx == 1), "split"] = "drop"
if A.exclude_early_deaths > 0:
    n0 = len(d)
    d = d[d.y_los_days * 24.0 >= A.exclude_early_deaths].reset_index(drop=True)
    print(f"exclude-early-deaths (<{A.exclude_early_deaths:g}h): {n0:,} -> {len(d):,} admissions, "
          f"mortality {d.y_mortality.mean()*100:.2f}%", flush=True)
if A.mortality_horizon_days > 0:
    if A.inject_labels:
        raise ValueError("--mortality-horizon-days is incompatible with --inject-labels: "
                         "the injected file does not contain event times")
    d["y_mortality_target"] = (
        d.y_mortality.eq(1) & d.y_los_days.le(A.mortality_horizon_days)
    ).astype(np.float32)
    print(f"fixed mortality horizon: death by admission day {A.mortality_horizon_days:g}; "
          f"positive rate {d.y_mortality_target.mean()*100:.2f}%", flush=True)
else:
    d["y_mortality_target"] = d.y_mortality.astype(np.float32)
print("split:", d.split.value_counts().to_dict(), flush=True)

INJ = None
if A.inject_labels:
    inj = pd.read_parquet(A.inject_labels).set_index("hadm_id")
    hit = d.hadm_id.isin(inj.index) & (d.split == "drop")
    d.loc[hit, "split"] = "train_inj"
    INJ = inj
    print(f"label injection: {int(hit.sum()):,} dropped cold-dx rows rejoin training "
          f"with simulated labels", flush=True)

# ------------------------------------------------------------------ history block (cold-user)
d = d.sort_values(["subject_id", "admittime"]).reset_index(drop=True)
g = d.groupby("subject_id")
d["prev_dischtime"] = g.dischtime.shift(1)
d["days_since_last_discharge"] = (d.admittime - d.prev_dischtime).dt.total_seconds() / 86400.0
d["prior_los_mean"] = g.y_los_days.transform(lambda s: s.shift(1).expanding().mean())
d["prior_mort_free"] = d.n_prior_admissions.clip(0, 20)
HIST = ["n_prior_admissions", "days_since_last_discharge", "prior_los_mean", "prior_mort_free"]
d["history_missing"] = d[HIST].isna().all(axis=1).astype(int)
d.loc[d.cold_user_first_admission == 1, "history_missing"] = 1
for c in HIST: d[c] = d[c].fillna(0.0)

# ------------------------------------------------------------------ features
CATS = ["gender", "race", "insurance", "language", "marital_status",
        "admission_type", "admission_location"]
d["icd3"] = d.primary_icd.astype(str).str.strip().str[:3]
tr = d[d.split == "train"]
cat_maps, cat_arr = {}, []
for c in CATS:
    vocab = {v: i + 1 for i, v in enumerate(sorted(tr[c].dropna().unique()))}  # 0 = unseen/missing
    cat_maps[c] = vocab
    cat_arr.append(d[c].map(vocab).fillna(0).astype(np.int64).values)

# dx: exact code id (cold codes are absent from train -> stays at index 0) + ICD chapter prefix
dx_vocab = {v: i + 1 for i, v in enumerate(sorted(tr.primary_icd.dropna().astype(str).unique()))}
i3_vocab = {v: i + 1 for i, v in enumerate(sorted(tr.icd3.dropna().unique()))}
dx_id = d.primary_icd.astype(str).map(dx_vocab).fillna(0).astype(np.int64).values
i3_id = d.icd3.map(i3_vocab).fillna(0).astype(np.int64).values
if A.dx_mode == "strata":
    dx_id = np.zeros_like(dx_id); i3_id = np.zeros_like(i3_id)
d["dx_cold_flag"] = (dx_id == 0).astype(int)
print(f"dx vocab={len(dx_vocab):,} icd3 vocab={len(i3_vocab):,}; "
      f"{d.dx_cold_flag.mean()*100:.1f}% of admissions carry an untrained dx id", flush=True)

# dx frequency from TRAIN ONLY (the cohort column is computed over everything -> leakage)
tr_freq = tr.primary_icd.astype(str).value_counts()
d["dx_freq_train"] = d.primary_icd.astype(str).map(tr_freq).fillna(0.0)

NUM = ["age"] + HIST + ["dx_freq_train"]
d["dx_freq_train"] = np.log1p(d.dx_freq_train)
X_num = d[NUM].astype(np.float32).values
mu, sd = X_num[d.split == "train"].mean(0), X_num[d.split == "train"].std(0) + 1e-6
X_num = (X_num - mu) / sd
AVAIL = np.stack([1 - d.history_missing.values, 1 - d.dx_cold_flag.values,
                  np.ones(len(d))], 1).astype(np.float32)   # [history, dx-id, static]

LABS = None
if A.labsfeat:
    lf = pd.read_parquet(A.labsfeat).set_index("hadm_id")
    if A.lab_group:
        GROUPS = {
            "renal": ["creatinine","bun","sodium","potassium","chloride","bicarbonate",
                      "glucose","calcium","magnesium","phosphate"],
            "heme": ["hematocrit","hemoglobin","platelets","wbc","mch","rdw"],
            "coag": ["inr","pt","ptt"],
            "hepatic": ["bilirubin_total","alt","ast","albumin"],
            "perfusion": ["lactate"],
            # the two global summaries belong to no family; kept as exact names so the
            # "measurement intensity, not physiology" reading can be priced on its own
            "count": ["lab_n", "lab_abn_frac"],
            # lab_n alone is the pure care-process variable; lab_abn_frac is derived
            # from analyte values via MIMIC's reference-range flag, so the two must be
            # separable before either is called "measurement intensity"
            "labn": ["lab_n"],
            "abnfrac": ["lab_abn_frac"],
        }
        keep = ([c for c in lf.columns if c in GROUPS[A.lab_group]]
                if A.lab_group in ("count", "labn", "abnfrac")
                else [c for c in lf.columns
                      if any(c.startswith(a_ + "_") for a_ in GROUPS[A.lab_group])])
        lf = lf[keep]
        print(f"lab group '{A.lab_group}': {len(keep)} of 74 features", flush=True)
    lidx = d.hadm_id.map({h: i for i, h in enumerate(lf.index)})
    lok = lidx.notna().values                                        # row has >=1 lab (78.7%)
    Lraw = np.full((len(d), lf.shape[1]), np.nan, np.float32)
    Lraw[lok] = lf.values[lidx[lok].astype(int).values].astype(np.float32)
    # per-ANALYTE missingness is common (not every patient gets every test) -> use nan-aware
    # winsorize/standardize so one column's NaNs cannot poison its own mean/std, then mean-impute
    trl = (d.split == "train").values & lok
    with np.errstate(invalid="ignore"):
        lo = np.nanpercentile(Lraw[trl], 1, axis=0); hi = np.nanpercentile(Lraw[trl], 99, axis=0)
        Lraw = np.clip(Lraw, lo, hi)
        lmu = np.nanmean(Lraw[trl], axis=0); lsd = np.nanstd(Lraw[trl], axis=0) + 1e-6
        lmu = np.nan_to_num(lmu); lsd = np.where(np.isfinite(lsd) & (lsd > 1e-6), lsd, 1.0)
        LABS = ((Lraw - lmu) / lsd).astype(np.float32)
    LABS = np.nan_to_num(LABS, nan=0.0)                               # per-analyte missing -> 0 (mean)
    LABS[~lok] = 0.0                                                  # no labs at all -> 0, gated off
    AVAIL = np.concatenate([AVAIL, lok.astype(np.float32)[:, None]], 1)
    assert np.isfinite(LABS).all(), "labs block still has non-finite values after imputation"
    print(f"labs block: {lf.shape[1]} features, coverage {lok.mean()*100:.1f}%", flush=True)

DXT = None
if A.dxemb:
    demb = np.load(A.dxemb); did = pd.read_parquet(A.dxids)["primary_icd"].astype(str).values
    dpos = {c: i for i, c in enumerate(did)}
    didx = d.primary_icd.astype(str).map(dpos)
    DXT = np.zeros((len(d), demb.shape[1]), np.float32)
    dok = didx.notna().values
    DXT[dok] = demb[didx[dok].astype(int).values]
    # dx text is CONTENT: known for every coded admission, cold or not -> availability is
    # coverage of the code table, not of training history
    AVAIL = np.concatenate([AVAIL, dok.astype(np.float32)[:, None]], 1)
    print(f"dx-text embeddings attached for {dok.mean()*100:.1f}% of admissions", flush=True)

TXT = None
if A.textemb:
    emb = np.load(A.textemb); tid = pd.read_parquet(A.textids)["hadm_id"].values
    pos = {h: i for i, h in enumerate(tid)}
    idx = d.hadm_id.map(pos)
    TXT = np.zeros((len(d), emb.shape[1]), np.float32)
    ok = idx.notna().values
    TXT[ok] = emb[idx[ok].astype(int).values]
    AVAIL = np.concatenate([AVAIL, ok.astype(np.float32)[:, None]], 1)
    NOTE_OK = ok.copy()          # ClinicalBERT is trained and scored on this subset only
    print(f"text embeddings attached for {ok.mean()*100:.1f}% of admissions", flush=True)

Y_M = d.y_mortality_target.values.astype(np.float32)
M_L = np.ones(len(d), np.float32)                        # LOS loss mask (injected rows: no LOS)
W_INJ = np.ones(len(d), np.float32)
Y_R = d.y_readmit_30d.values.astype(np.float32)          # NaN where unobserved
if A.readmit_basis == "naive":
    # resurrect the pre-correction label: censored last admissions count as "no readmission"
    cens = d.readmit_censored.values == 1
    Y_R = np.where(cens & np.isnan(Y_R), 0.0, Y_R)
    print(f"NAIVE readmit basis: {int(cens.sum()):,} censored rows refilled with 0", flush=True)
M_R = (~np.isnan(Y_R)).astype(np.float32); Y_R = np.nan_to_num(Y_R)
# Evaluation mask. Under the naive basis the refilled rows are legitimate TRAINING targets but
# they are not observed outcomes, so scoring them would compare the two protocols on different
# test rows (105,360 at 20.0% prevalence against 63,062 at 33.5%). Keep the uncensored mask
# separate so the arms differ only in how the training label was built.
M_R_EVAL = (~np.isnan(d.y_readmit_30d.values.astype(np.float32))).astype(np.float32)
if INJ is not None:
    ii = d.split == "train_inj"
    ord_ = d.loc[ii, "hadm_id"]
    Y_M[ii.values] = INJ.loc[ord_, "y_mort"].values.astype(np.float32)
    yr_inj = INJ.loc[ord_, "y_readmit"].values.astype(np.float32)
    Y_R[ii.values] = np.nan_to_num(yr_inj)
    M_R[ii.values] = (~np.isnan(yr_inj)).astype(np.float32)
    M_L[ii.values] = 0.0
    W_INJ[ii.values] = INJ.loc[ord_, "conf"].values.astype(np.float32)
    d.loc[ii, "split"] = "train"                          # from here on they are train rows
Y_L = np.log1p(d.y_los_days.values.astype(np.float32))
los_mu, los_sd = Y_L[d.split == "train"].mean(), Y_L[d.split == "train"].std()

# ---- retrieval-evidence block: outcomes of the K nearest warm TRAIN admissions ----
KNN_F = None
if A.knn:
    tknn = time.time()
    q = []
    if TXT is not None: q.append(TXT)
    if DXT is not None: q.append(DXT)
    assert q, "--knn needs --textemb and/or --dxemb"
    Q = np.concatenate(q, 1)
    Q = Q / (np.linalg.norm(Q, axis=1, keepdims=True) + 1e-9)
    tr_mask = (d.split == "train").values
    tr_idx = np.where(tr_mask)[0]
    Qg = torch.tensor(Q, device=DEV, dtype=torch.float16)
    Ng = Qg[tr_idx]
    subj = d.subject_id.values
    tr_subj = torch.tensor(subj[tr_idx].astype(np.int64), device=DEV)
    ym_t = torch.tensor(Y_M[tr_idx], device=DEV)
    yr_t = torch.tensor(np.nan_to_num(d.y_readmit_30d.values[tr_idx]), device=DEV, dtype=torch.float32)
    mr_t = torch.tensor((~np.isnan(d.y_readmit_30d.values[tr_idx])).astype(np.float32), device=DEV)
    yl_t = torch.tensor(np.log1p(d.y_los_days.values[tr_idx]), device=DEV, dtype=torch.float32)
    feats = torch.zeros(len(d), 6, device=DEV)
    B_ = 2048
    for k0 in range(0, len(d), B_):
        k1 = min(k0 + B_, len(d))
        sims = (Qg[k0:k1] @ Ng.T).float()                       # (b, n_train)
        qs = torch.tensor(subj[k0:k1].astype(np.int64), device=DEV)
        sims[qs.unsqueeze(1) == tr_subj.unsqueeze(0)] = -1e4    # exclude same patient
        top = torch.topk(sims, A.knn_k, dim=1)
        w = torch.softmax(top.values * 10, 1)
        ti = top.indices
        mort_n = (w * ym_t[ti]).sum(1)
        mr_n = mr_t[ti]
        readm_n = (w * yr_t[ti] * mr_n).sum(1) / (w * mr_n).sum(1).clamp(min=1e-6)
        los_n = (w * yl_t[ti]).sum(1)
        feats[k0:k1, 0] = mort_n
        feats[k0:k1, 1] = readm_n
        feats[k0:k1, 2] = los_n
        feats[k0:k1, 3] = top.values.max(1).values
        feats[k0:k1, 4] = top.values.mean(1)
        feats[k0:k1, 5] = (w * mr_n).sum(1)
    KNN_F = feats.cpu().numpy().astype(np.float32)
    kmu = KNN_F[tr_mask].mean(0); ksd = KNN_F[tr_mask].std(0) + 1e-6
    KNN_F = (KNN_F - kmu) / ksd
    del Qg, Ng; torch.cuda.empty_cache()
    AVAIL = np.concatenate([AVAIL, np.ones((len(d), 1), np.float32)], 1)
    print(f"knn evidence block: K={A.knn_k} over {len(tr_idx):,} train admissions "
          f"({time.time()-tknn:.0f}s)", flush=True)

AGT = None
if A.agentemb:
    aemb = np.load(A.agentemb); aid = pd.read_parquet(A.agentids)["hadm_id"].values
    apos = {h: i for i, h in enumerate(aid)}
    aidx = d.hadm_id.map(apos)
    AGT = np.zeros((len(d), aemb.shape[1]), np.float32)
    aok = aidx.notna().values
    AGT[aok] = aemb[aidx[aok].astype(int).values]
    AVAIL = np.concatenate([AVAIL, aok.astype(np.float32)[:, None]], 1)
    print(f"agent-evidence embeddings attached for {aok.mean()*100:.1f}% of admissions", flush=True)

# ---- IPCW: reweight the observed-readmission loss by 1/P(follow-up observed | x) ----
